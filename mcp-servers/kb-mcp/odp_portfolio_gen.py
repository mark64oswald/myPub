"""odp_portfolio_gen.py — ``/kb-dp-portfolio``: product ideas into an ODPC catalog + ODPG graph (2026-11).

Input is a portfolio name plus short lists:

    products    ["Customer churn scores: weekly churn risk per customer", ...]
    use_cases   ["Retention campaigns: target at-risk customers => Customer churn scores", ...]
    objectives  ["Reduce churn: keep more paying customers => Retention campaigns", ...]

``=>`` links an entry to the things it uses (a use case to products, an
objective to use cases). Without links, every use case uses every product
and every objective is supported by every use case; without use cases, each
product gets one; without objectives, the portfolio gets one.

Output:

    <package>/
      products/<p>.odps.yaml                ODPS 4.2 draft per product
      contracts/<p>.odcs.yaml               ODCS v3.1.0 placeholder contract per product
      catalog/fragments/*.yaml              ODPC product references, use cases, objectives + KPIs
      catalog/<portfolio>.odpc.yaml         built from the fragments (when the SDK is installed)
      graph/<portfolio>.odpg.yaml           ODPG value graph: uses / supports / contributesTo / measures
      recipes/validate.recipe.yaml          ODPR recipe: validate everything, build the catalog
      Makefile, README.md, guidance.md, _provenance.md, _validation.md,
      _prompts/fill-portfolio.md

Deterministic. Every YAML file is checked with the open-data-products SDK
when it is on PATH (``_validation.md``); ODCS files against the vendored schema.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from types import SimpleNamespace
from typing import Any, Optional, Sequence

import duckdb
import yaml

import kb_scaffold as ks
import odp_gen as og
import odp_profile
from generator import GenFile, GenPlan, GenUnit, Generator, ValidationIssue

GENERATOR_TYPE = "dp_portfolio"


@dataclass
class Item:
    name: str
    description: str
    links: list[str] = field(default_factory=list)   # names this item uses / is supported by

    @property
    def slug(self) -> str:
        return og.slug(self.name)


def parse_items(entries: Sequence[str]) -> list[Item]:
    out: list[Item] = []
    for raw in entries or []:
        text, _, links = str(raw).partition("=>")
        name, sep, desc = text.partition(":")
        name = name.strip()
        if not name:
            continue
        out.append(Item(name, desc.strip() if sep else "",
                        [x.strip() for x in links.split(",") if x.strip()]))
    return out


def _resolve_links(item: Item, pool: Sequence[Item]) -> list[Item]:
    if not item.links:
        return list(pool)
    by = {p.name.lower(): p for p in pool} | {p.slug: p for p in pool}
    return [by[k] for k in (link.lower() for link in item.links) if k in by] or \
           [by[og.slug(link)] for link in item.links if og.slug(link) in by]


