class PortfolioDecomposer:
    def decompose(self, conn: duckdb.DuckDBPyConnection, resolver: Any, query: str, **kw: Any):
        products = parse_items(kw.get("products") or [])
        use_cases = parse_items(kw.get("use_cases") or [])
        objectives = parse_items(kw.get("objectives") or [])
        name = kw.get("portfolio_name") or query
        text = " ".join([query, *(kw.get("products") or []), kw.get("platform") or ""])
        tm = None
        for topic in ("Data Product Portfolio", "Data Product Portfolio Management", "Data Product"):
            tm = ks.topic_material(conn, resolver, topic, max_procedures=6)
            if tm:
                break
        cites = ks.doc_citations(conn, og.ODPC_SOURCES + og.ODPG_SOURCES,
                                 keywords=("use case", "objective", "kpi", "edge"), per_source=3)
        return {"query": query, "name": name, "products": products, "use_cases": use_cases,
                "objectives": objectives, "topic": tm, "citations": cites,
                "platform": (kw.get("platform") or og.detect_platform(text)).lower()}


class PortfolioPlanner:
    def plan(self, conn: duckdb.DuckDBPyConnection, d: dict, *,
             package_name: Optional[str] = None, **_: Any) -> GenPlan:
        portfolio = og.title(d["name"]) if d["name"].islower() else d["name"]
        pslug = og.slug(d["name"])
        plan = GenPlan(generator_type=GENERATOR_TYPE, package_name=package_name or pslug,
                       domain="data product portfolio", source_query=d["query"])
        products: list[Item] = d["products"]
        if not products:
            plan.package_metadata = {"n_products": 0}
            return plan
        use_cases: list[Item] = d["use_cases"] or [
            Item(f"{p.name} use case", f"Who uses {p.name} and for what.", [p.name])
            for p in products]
        objectives: list[Item] = d["objectives"] or [
            Item(f"{portfolio} objective", "The business outcome the portfolio serves.")]
        uc_products = {uc.slug: _resolve_links(uc, products) for uc in use_cases}
        obj_use_cases = {o.slug: _resolve_links(o, use_cases) for o in objectives}
        unlinked = [link for item in use_cases + objectives for link in item.links
                    if og.slug(link) not in {x.slug for x in products + use_cases}]
        if unlinked:
            plan.notes.append("links that match no product or use case (ignored): "
                              + ", ".join(sorted(set(unlinked))))

        catalog_path, graph_path = f"catalog/{pslug}.odpc.yaml", f"graph/{pslug}.odpg.yaml"
        files: dict[str, str] = {}
        for p in products:
            ucs = [uc for uc in use_cases if p in uc_products[uc.slug]]
            objs = [o for o in objectives if any(uc in obj_use_cases[o.slug] for uc in ucs)]
            kpi_obj = objs[0] if objs else objectives[0]
            files.update(product_files(
                p, platform=d["platform"],
                kpi=(f"kpi-{kpi_obj.slug}", f"{kpi_obj.name} KPI"),
                use_case_paths=[f"catalog/fragments/use_case_{uc.slug}.yaml" for uc in ucs]))
        for uc in use_cases:
            files[f"catalog/fragments/use_case_{uc.slug}.yaml"] = use_case_fragment(
                uc, uc_products[uc.slug])
        for o in objectives:
            files[f"catalog/fragments/business_objective_{o.slug}.yaml"] = objective_fragment(o)
        files[graph_path] = graph_doc(portfolio, products, use_cases, uc_products, objectives,
                                      obj_use_cases)
        files["recipes/validate.recipe.yaml"] = recipe_doc(portfolio, products, catalog_path,
                                                           graph_path)
        cat_id = f"CAT-{og.upper_id(pslug)}"
        files["Makefile"] = makefile(products, catalog_path, graph_path, cat_id)

        # Checks: ODCS schema per contract, then the SDK over everything at once.
        checks = [og.check_odcs(yaml.safe_load(v), k) for k, v in files.items()
                  if k.startswith("contracts/")]
        cmds: list[tuple[str, Sequence[str]]] = [
            (f"products/{p.slug}.odps.yaml", ["validate", f"products/{p.slug}.odps.yaml"])
            for p in products]
        cmds += [(graph_path, ["validate", graph_path]),
                 ("recipes/validate.recipe.yaml", ["recipe", "validate",
                                                   "recipes/validate.recipe.yaml"]),
                 (catalog_path, ["odpc-build", "catalog/fragments", "-o", catalog_path,
                                 "--id", cat_id])]
        sdk_results, built = _sdk_check_and_build(files, cmds, catalog_path)
        checks += sdk_results
        if built:
            files[catalog_path] = built

        tm: Optional[ks.TopicMaterial] = d["topic"]
        files["README.md"] = readme(portfolio, d["query"], products, use_cases, uc_products,
                                    objectives, obj_use_cases, catalog_path, graph_path)
        files["guidance.md"] = guidance(tm, d["citations"])
        files["_provenance.md"] = (
            f"# Provenance: {portfolio}\n\nBuilt from {len(products)} product ideas, "
            f"{len(d['use_cases'])} use cases and {len(d['objectives'])} objectives given "
            "(defaults filled the rest).\n\n"
            + ks.render_citations(d["citations"], "Spec sections")
            + "\n" + ks.render_citations(tm.sources if tm else [], "Knowledge-base sources"))
        files["_validation.md"] = og.render_checks(f"Portfolio checks: {portfolio}", checks)
        files["_prompts/fill-portfolio.md"] = FILL_PROMPT.format(portfolio=portfolio,
                                                                 graph=graph_path)
        files[".gitignore"] = "build/\n.venv/\n.DS_Store\n"

        plan.package_metadata = {
            "n_products": len(products), "n_use_cases": len(use_cases),
            "n_objectives": len(objectives), "platform": d["platform"],
            "catalog_built": bool(built), "check_errors": og.check_errors(checks),
            "checks_run": sum(1 for c in checks if c.ok is not None),
        }
        for p in products:
            plan.units.append(GenUnit(unit_type="data_product", name=p.name, logical_key=p.slug,
                                      content_markdown=files[f"products/{p.slug}.odps.yaml"],
                                      metadata={"description": p.description}))
        plan.units[0].sources = [(c.source_type, c.source_id, 1.0, 1.0, None)
                                 for c in list(d["citations"]) + (tm.sources if tm else [])]
        for path, content in files.items():
            plan.files.append(GenFile(filename=path, content=content,
                                      purpose=path.split("/")[0].split(".")[0]))
        return plan


def _sdk_check_and_build(files: dict[str, str], cmds: Sequence[tuple[str, Sequence[str]]],
                         catalog_path: str) -> tuple[list[og.CheckResult], Optional[str]]:
    """Run the SDK checks; return the built catalog text when odpc-build succeeded."""
    import tempfile  # noqa: PLC0415
    from pathlib import Path  # noqa: PLC0415

    if og.sdk_path() is None:
        return og.sdk_check(files, cmds), None
    with tempfile.TemporaryDirectory(prefix="mypub-odp-") as tmp:
        root = Path(tmp)
        for rel, content in files.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_text(content)
        results: list[og.CheckResult] = []
        for label, args in cmds:
            code, text = og.run_sdk(args, root)
            msgs = [] if code == 0 else [ln for ln in text.splitlines()
                                         if ln.strip() and not ln.startswith("✓")][-8:]
            results.append(og.CheckResult(f"sdk {args[0]}", label,
                                          None if code is None else code == 0, msgs))
        graph = next((label for label, args in cmds if label.startswith("graph/")), None)
        if graph:
            code, text = og.run_sdk(["odpg-analyze", graph, "--json"], root)
            try:
                analysis = json.loads(text).get("analysis", {}) if code == 0 else {}
            except ValueError:
                analysis = {}
            findings = [f"{k}: {', '.join(map(str, v))}" for k, v in analysis.items() if v]
            results.append(og.CheckResult("sdk odpg-analyze (advice, not errors)", graph, True,
                                          findings))
        built = None
        if (root / catalog_path).is_file():
            code, text = og.run_sdk(["validate", catalog_path], root)
            results.append(og.CheckResult("sdk validate", catalog_path, code == 0,
                                          [] if code == 0 else text.splitlines()[-5:]))
            built = (root / catalog_path).read_text()
        return results, built


class PortfolioValidator:
    def validate(self, conn: duckdb.DuckDBPyConnection, plan: GenPlan) -> list[ValidationIssue]:
        meta = plan.package_metadata
        if not meta.get("n_products"):
            return [ValidationIssue("", "error", "give at least one product idea (products=[...])")]
        out = [ValidationIssue("", "error", m) for m in meta.get("check_errors", [])]
        if not meta.get("checks_run"):
            out.append(ValidationIssue("", "warning",
                                       "no SDK or jsonschema here; run `make all` to check"))
        return out


def make_dp_portfolio_generator() -> Generator:
    return Generator(generator_type=GENERATOR_TYPE, decomposer=PortfolioDecomposer(),
                     planner=PortfolioPlanner(), ranking_mode="generation",
                     validator=PortfolioValidator(), materializer=ks.TreeMaterializer())
