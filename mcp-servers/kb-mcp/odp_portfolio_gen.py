def product_files(p: Item, *, platform: str, kpi: tuple[str, str],
                  use_case_paths: Sequence[str]) -> dict[str, str]:
    """ODPS draft, ODCS placeholder and ODPC product reference for one product."""
    ctx = SimpleNamespace(project_name=p.name, slug=p.slug, pkg=og.snake(p.name), purpose="",
                          ctx_summary="", request=p.description or p.name,
                          data={"platform": platform})
    odps = yaml.safe_load(odp_profile.odps_product(ctx))
    strat = odps["product"]["productStrategy"]
    strat["objectives"] = [{"en": f"Serve {path}"} for path in use_case_paths] or \
        [{"en": "TODO: name the use case this product serves."}]
    strat["contributesToKPI"]["id"], strat["contributesToKPI"]["name"] = kpi
    return {
        f"products/{p.slug}.odps.yaml": og.dump_yaml(odps, (
            f"ODPS 4.2 draft for {p.name}. Generated by myPub /kb-dp-portfolio.\n"
            f"{og.MARKER}: replace the draft SLA, quality, KPI and access values.")),
        f"contracts/{p.slug}.odcs.yaml": odp_profile.odcs_contract(ctx),
        f"catalog/fragments/product_reference_{p.slug}.yaml": odp_profile.odpc_product_ref(ctx),
    }


def use_case_fragment(uc: Item, products: Sequence[Item]) -> str:
    return og.dump_yaml({"useCase": {
        "id": f"uc-{uc.slug}",
        "name": {"en": uc.name},
        "description": {"en": uc.description or f"TODO: describe {uc.name}."},
        "stakeholders": ["TODO: who needs this"],
        "decision": {"en": "TODO: the decision this use case supports."},
        "expectedOutcome": {"en": "TODO: the measurable change it should produce."},
        "dataNeeds": {"summary": {"en": ", ".join(p.name for p in products)},
                      "items": [p.slug for p in products]},
        "status": "draft", "priority": "medium",
    }}, f"ODPC use case. {og.MARKER}: real stakeholders and decision.")


def objective_fragment(obj: Item) -> str:
    return og.dump_yaml({"businessObjective": {
        "id": f"obj-{obj.slug}",
        "name": {"en": obj.name},
        "description": {"en": obj.description or f"TODO: describe {obj.name}."},
        "owner": {"role": "Business owner"},
        "kpis": [{"id": f"kpi-{obj.slug}", "name": {"en": f"{obj.name} KPI"},
                  "unit": "percent", "target": {"value": 0}}],
        "status": "draft", "priority": "medium",
    }}, f"ODPC business objective with its KPI. {og.MARKER}: real target and dates.")


def graph_doc(portfolio: str, products: Sequence[Item], use_cases: Sequence[Item],
              uc_products: dict[str, list[Item]], objectives: Sequence[Item],
              obj_use_cases: dict[str, list[Item]]) -> str:
    pid = og.upper_id(og.slug(portfolio))
    nodes: list[dict[str, Any]] = []
    edges: list[dict[str, Any]] = []
    for p in products:
        nodes.append({"id": f"DP-{og.upper_id(p.slug)}", "type": "DataProduct",
                      "$ref": f"../products/{p.slug}.odps.yaml"})
    for uc in use_cases:
        nodes.append({"id": f"UC-{og.upper_id(uc.slug)}", "type": "UseCase",
                      "$ref": f"../catalog/fragments/use_case_{uc.slug}.yaml"})
        for p in uc_products[uc.slug]:
            edges.append({"from": f"UC-{og.upper_id(uc.slug)}", "to": f"DP-{og.upper_id(p.slug)}",
                          "type": "uses", "confidence": "high"})
    for obj in objectives:
        oid, kid = f"OBJ-{og.upper_id(obj.slug)}", f"KPI-{og.upper_id(obj.slug)}"
        ref = f"../catalog/fragments/business_objective_{obj.slug}.yaml"
        nodes += [{"id": oid, "type": "BusinessObjective", "$ref": ref},
                  {"id": kid, "type": "KPI", "$ref": f"{ref}#kpi-{obj.slug}"}]
        edges.append({"from": kid, "to": oid, "type": "measures", "confidence": "high"})
        contributing: dict[str, Item] = {}
        for uc in obj_use_cases[obj.slug]:
            edges.append({"from": f"UC-{og.upper_id(uc.slug)}", "to": oid, "type": "supports",
                          "confidence": "high"})
            for p in uc_products[uc.slug]:
                contributing[p.slug] = p
        for p in contributing.values():
            edges.append({"from": f"DP-{og.upper_id(p.slug)}", "to": oid, "type": "contributesTo",
                          "confidence": "medium"})
    doc = {"schema": odp_profile.ODPG_SCHEMA, "version": "1.0", "kind": "Graph", "graph": {
        "metadata": {"id": f"GRAPH-{pid}", "name": {"en": f"{portfolio} value graph"},
                     "description": {"en": "Products, use cases, objectives and KPIs, connected."}},
        "nodes": nodes, "edges": edges}}
    return og.dump_yaml(doc, (
        "ODPG value graph. Edge types are ODPV relationship terms; check one with\n"
        "open-data-products odpv-relationship <from-type> <type> <to-type>.\n"
        "contributesTo edges are derived (product used by a use case that supports the\n"
        "objective), so they carry medium confidence until someone confirms them."))


def recipe_doc(portfolio: str, products: Sequence[Item], catalog_path: str, graph_path: str
               ) -> str:
    pid = og.upper_id(og.slug(portfolio))
    steps = [{"id": f"validate-{p.slug}", "command": "validate",
              "with": {"document": f"products/{p.slug}.odps.yaml"}} for p in products]
    steps.append({"id": "validate-graph", "command": "validate", "with": {"document": graph_path}})
    steps.append({"id": "build-catalog", "command": "odpc.build",
                  "with": {"input": "catalog/fragments", "output": catalog_path,
                           "id": f"CAT-{pid}", "validate": True}})
    doc = {"schema": odp_profile.ODPR_SCHEMA, "version": "1.0", "kind": "Recipe", "recipe": {
        "metadata": {"id": f"RCP-{pid}-VALIDATE", "name": {"en": f"Validate {portfolio}"},
                     "description": {"en": "Validate every product and the graph, then build "
                                           "the ODPC catalog."},
                     "tags": ["validation", "portfolio"]},
        "version": "1.0.0", "type": "ci", "steps": steps,
        "gates": [{"id": "schemas-valid", "type": "validation", "required": True,
                   "description": "Every file validates against its schema."}],
        "review": {"required": True, "mode": "human",
                   "instructions": "The portfolio owner reviews priorities and KPI targets."},
        "runPolicy": {"stopOnFailure": True}}}
    return og.dump_yaml(doc, "ODPR recipe. Run: open-data-products recipe dry-run "
                             "recipes/validate.recipe.yaml")


def makefile(products: Sequence[Item], catalog_path: str, graph_path: str, cat_id: str) -> str:
    val = "".join(f"\t$(ODP) validate products/{p.slug}.odps.yaml\n" for p in products)
    return (
        "ODP ?= open-data-products\n\n.PHONY: validate catalog analyze recipe all\n\n"
        f"validate:\n{val}\t$(ODP) validate {graph_path}\n"
        "\t$(ODP) recipe validate recipes/validate.recipe.yaml\n\n"
        f"catalog:\n\t$(ODP) odpc-build catalog/fragments -o {catalog_path} --id {cat_id}\n"
        f"\t$(ODP) validate {catalog_path}\n\n"
        f"analyze:\n\t$(ODP) odpg-analyze {graph_path}\n\n"
        "recipe:\n\t$(ODP) recipe dry-run recipes/validate.recipe.yaml\n\n"
        "all: validate catalog analyze recipe\n")


def readme(portfolio: str, description: str, products: Sequence[Item], use_cases: Sequence[Item],
           uc_products: dict[str, list[Item]], objectives: Sequence[Item],
           obj_use_cases: dict[str, list[Item]], catalog_path: str, graph_path: str) -> str:
    rows = ["| Objective | Supported by use case | Uses data product |", "|---|---|---|"]
    for obj in objectives:
        for uc in obj_use_cases[obj.slug]:
            rows.append(f"| {obj.name} | {uc.name} | "
                        f"{', '.join(p.name for p in uc_products[uc.slug])} |")
    return f"""\
# {portfolio}

{description}

A data product portfolio in the Open Data Product standards: {len(products)} products
(ODPS 4.2), {len(use_cases)} use cases and {len(objectives)} business objectives
(ODPC 1.0 fragments), connected in an ODPG 1.0 value graph.

## How value flows

{chr(10).join(rows)}

## Files

| Path | What it is |
|---|---|
| `products/` | One ODPS draft per product (source of truth for each product) |
| `contracts/` | One ODCS placeholder contract per product |
| `catalog/fragments/` | ODPC product references, use cases, objectives + KPIs |
| `{catalog_path}` | The ODPC catalog built from the fragments (`make catalog`) |
| `{graph_path}` | ODPG value graph |
| `recipes/validate.recipe.yaml` | ODPR recipe: validate, then build |
| `guidance.md` | What the library says about portfolios |

## Check and build

```bash
pip install open-data-products
make all        # validate, build the catalog, analyze the graph, dry-run the recipe
```

`open-data-products odpg-generate {graph_path} --output graph.html` draws the graph.
"""


def guidance(tm: Optional[ks.TopicMaterial], cites: Sequence[ks.Citation]) -> str:
    lines = ["# Portfolio guidance", ""]
    if tm and tm.description:
        lines += [f"**{tm.name}.** " + " ".join(tm.description.split()), ""]
    if tm and tm.procedures:
        lines += ["## Procedures from the library", ""]
        for p in tm.procedures:
            src = f" _({p.source.label})_" if p.source else ""
            lines.append(f"- **{p.name}.** {ks.first_sentence(p.steps, 240)}{src}")
        lines.append("")
    lines += ["## Review before sharing", "",
              "- [ ] Every product has an owner and a real value proposition.",
              "- [ ] Every use case names a decision and who makes it.",
              "- [ ] Every objective has a KPI with a baseline and a target date.",
              "- [ ] Derived `contributesTo` edges in the graph are confirmed or removed.",
              "- [ ] Priorities (`portfolioPriority`, `priority`) reflect the real ranking.", ""]
    lines.append(ks.render_citations(cites, "Spec sections behind this layout"))
    return "\n".join(lines)


FILL_PROMPT = """\
# Fill in the {portfolio} portfolio

Edit the files in place; keep every one valid (`make validate catalog`).

- Products (`products/*.odps.yaml`): real descriptions, owners, access and
  SLA values. Leave a TODO and add a question to README.md when unsure.
- Use cases and objectives (`catalog/fragments/`): real stakeholders,
  decisions and KPI targets. Never invent numbers.
- Graph (`{graph}`): confirm or delete the derived `contributesTo` edges; add
  dependsOn / governedBy edges you know about. Keep node ids stable.
- Names: prefer ODPV terms (`open-data-products odpv-resolve "<term>"`).
"""


