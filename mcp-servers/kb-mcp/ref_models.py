def proto_imports(text: str) -> list[str]:
    return re.findall(r'^\s*import\s+"([^"]+)"\s*;', text, re.M)


def _camel_snake(name: str) -> str:
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()


def parse_proto_model(files: dict[str, str], *, source: str = "ga4gh",
                      industry: str = "genomics", flavour: str = "phenopackets",
                      version: str = "2.0", name: str = "GA4GH Phenopackets v2",
                      origin_uri: str = "phenopackets/phenopacket-schema",
                      license_note: str = "BSD-3-Clause") -> RefModel:
    """Messages as entities (domain = .proto file stem), scalar and enum fields as
    columns. A singular message field becomes an FK column ``<field>_id``; a
    repeated one becomes an association table ``<parent>_<field>``."""
    messages: dict[str, tuple[str, list[tuple[bool, str, str]], str]] = {}  # name -> (domain, fields, comment)
    enums: set[str] = set()
    for path, text in files.items():
        domain = snake(Path(path).stem)
        body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        stack: list[tuple[str, str]] = []
        last_comment: list[str] = []
        pieces: list[tuple[str, str]] = []          # (code statement, comment)
        for raw in body.splitlines():
            comment = re.search(r"//\s?(.*)$", raw)
            code = re.sub(r"//.*$", "", raw)
            parts = [p.strip() for p in re.split(r"(?<=[{;])|(?=\})", code) if p.strip()]
            if not parts:
                pieces.append(("", comment.group(1).strip() if comment else ""))
            pieces += [(p, "") for p in parts]
        for line, comment_text in pieces:
            if not line:
                if comment_text:
                    last_comment.append(comment_text)
                continue
            m = re.match(r"(message|enum|oneof)\s+(\w+)\s*\{", line)
            if m:
                kind, nm = m.groups()
                if kind == "message":
                    full = nm if nm not in messages else f"{stack[-1][1]}{nm}" if stack else nm
                    messages.setdefault(full, (domain, [], " ".join(last_comment)[:400]))
                    stack.append(("message", full))
                elif kind == "enum":
                    enums.add(nm)
                    stack.append(("enum", nm))
                else:
                    stack.append(("oneof", nm))
                last_comment = []
                continue
            if line.startswith("}"):
                if stack:
                    stack.pop()
                last_comment = []
                continue
            owner = next((n for k, n in reversed(stack) if k == "message"), None)
            if owner and stack and stack[-1][0] != "enum":
                f = _PROTO_FIELD.match(line)
                if f:
                    rep, typ, fname = f.groups()
                    messages[owner][1].append((bool(rep and rep.strip() == "repeated"),
                                               typ.split(".")[-1] if not typ.startswith("map")
                                               else "map", fname))
            last_comment = []
    model = RefModel(source=source, industry=industry, flavour=flavour, version=version,
                     name=name, origin_uri=origin_uri, license_note=license_note)
    ents: dict[str, RefEntity] = {}
    for mname, (domain, _fields, comment) in messages.items():
        ename = _camel_snake(mname)
        ents[mname] = RefEntity(name=ename, domain=domain, display_name=mname,
                                description=comment, primary_key=f"{ename}_id",
                                attributes=[RefAttribute(name=f"{ename}_id", data_type="BIGINT",
                                                         is_pk=True,
                                                         description="Surrogate key.")])
    assoc: list[RefEntity] = []
    for mname, (domain, fields, _c) in messages.items():
        ent = ents[mname]
        for rep, typ, fname in fields:
            target = ents.get(typ)
            if target is None:
                dtype = "STRING" if typ in enums or typ == "map" else _PROTO_SCALAR.get(typ, "STRING")
                ent.attributes.append(RefAttribute(
                    name=fname, data_type=f"ARRAY<{dtype}>" if rep else dtype,
                    tags="enum" if typ in enums else ""))
            elif not rep:
                ent.attributes.append(RefAttribute(
                    name=f"{fname}_id", data_type="BIGINT",
                    fk_to=f"{target.key}.{target.primary_key}",
                    description=f"{fname} ({typ})"))
            else:
                an = f"{ent.name}_{fname}"
                assoc.append(RefEntity(
                    name=an, domain=domain, subdomain="association", primary_key=f"{an}_id",
                    description=f"{mname}.{fname}: repeated {typ}.",
                    attributes=[
                        RefAttribute(name=f"{an}_id", data_type="BIGINT", is_pk=True),
                        RefAttribute(name=f"{ent.name}_id", data_type="BIGINT",
                                     fk_to=f"{ent.key}.{ent.primary_key}"),
                        RefAttribute(name=f"{target.name}_id" if target is not ent
                                     else f"child_{target.name}_id", data_type="BIGINT",
                                     fk_to=f"{target.key}.{target.primary_key}"),
                        RefAttribute(name="ordinal", data_type="INT")]))
    model.entities = list(ents.values()) + assoc
    return model


_TABLE_RE = re.compile(
    r"CREATE\s+(?:OR\s+REPLACE\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([`\w.\"]+)\s*\(", re.I)
_FK_RE = re.compile(
    r"ALTER\s+TABLE\s+([`\w.\"]+)\s+ADD\s+CONSTRAINT\s+[`\w\"]+\s+FOREIGN\s+KEY\s*\(\s*([`\w\"]+)\s*\)"
    r"\s*REFERENCES\s+([`\w.\"]+)\s*\(\s*([`\w\"]+)\s*\)", re.I)
_INLINE_FK_RE = re.compile(
    r"FOREIGN\s+KEY\s*\(\s*([`\w\"]+)\s*\)\s*REFERENCES\s+([`\w.\"]+)\s*\(\s*([`\w\"]+)\s*\)", re.I)
_PK_RE = re.compile(r"PRIMARY\s+KEY\s*\(([^)]*)\)", re.I)
_COMMENT_RE = re.compile(r"COMMENT\s+'((?:[^']|'')*)'", re.I)


def _ident(text: str) -> list[str]:
    return [p.strip('`"') for p in text.split(".") if p.strip('`"')]


def _split_top(body: str) -> list[str]:
    """Split a column list on top-level commas, respecting parens and quotes
    ('' and "" escapes included)."""
    parts, depth, quote, cur, i = [], 0, None, [], 0
    while i < len(body):
        ch = body[i]
        if quote:
            cur.append(ch)
            if ch == quote:
                if body[i + 1:i + 2] == quote:
                    cur.append(body[i + 1])
                    i += 1
                else:
                    quote = None
        elif ch in "'\"`":
            quote = ch
            cur.append(ch)
        elif ch == "(":
            depth += 1
            cur.append(ch)
        elif ch == ")":
            depth -= 1
            cur.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur))
    return parts


def _close_paren(text: str, start: int) -> int:
    depth, i, quote = 0, start, None
    while i < len(text):
        ch = text[i]
        if quote:
            if ch == quote and text[i + 1:i + 2] != quote:
                quote = None
            elif ch == quote:
                i += 1
        elif ch in "'\"":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text) - 1


def parse_ddl_model(ddl: str, *, industry: str = "custom", name: str = "",
                    source: str = "user", flavour: str = "ddl", version: str = "1") -> RefModel:
    """Parse CREATE TABLE statements (Databricks/Unity Catalog style, or plain SQL)
    plus ``ALTER TABLE ... FOREIGN KEY`` constraints into a RefModel.

    The schema part of a three-part name becomes the entity's domain. Inline
    ``COMMENT '...'`` on columns and tables is kept as the description."""
    model = RefModel(source=source, industry=industry, flavour=flavour, version=version,
                     name=name or industry)
    by_key: dict[str, RefEntity] = {}
    for m in _TABLE_RE.finditer(ddl):
        ident = _ident(m.group(1))
        open_at = m.end() - 1
        close_at = _close_paren(ddl, open_at)
        body = ddl[open_at + 1:close_at]
        tail = ddl[close_at + 1:close_at + 4000].split(";", 1)[0]
        ent = RefEntity(name=snake(ident[-1]), domain=snake(ident[-2]) if len(ident) >= 2 else "")
        cm = _COMMENT_RE.match(tail.strip())
        if cm:
            ent.description = cm.group(1).replace("''", "'")
        pks: list[str] = []
        for part in _split_top(body):
            p = part.strip()
            if not p:
                continue
            up = p.upper()
            if up.startswith(("CONSTRAINT", "PRIMARY KEY", "FOREIGN KEY", "UNIQUE", "CHECK", "INDEX")):
                pk = _PK_RE.search(p)
                if pk:
                    pks += [snake(x.strip().strip('`"')) for x in pk.group(1).split(",")]
                fk = _INLINE_FK_RE.search(p)
                if fk:
                    col = snake(fk.group(1).strip('`"'))
                    tgt = _ident(fk.group(2))
                    for a in ent.attributes:
                        if a.name == col:
                            a.fk_to = ".".join(snake(x) for x in tgt[-2:] + [fk.group(3).strip('`"')])
                continue
            toks = p.split(None, 2)
            col = snake(toks[0].strip('`"'))
            dtype = toks[1] if len(toks) > 1 else ""
            desc = ""
            cm = _COMMENT_RE.search(p)
            if cm:
                desc = cm.group(1).replace("''", "'")
            ent.attributes.append(RefAttribute(name=col, data_type=dtype.upper(),
                                               is_pk="PRIMARY KEY" in up, description=desc))
        for a in ent.attributes:
            if a.name in pks:
                a.is_pk = True
        pk_cols = [a.name for a in ent.attributes if a.is_pk]
        ent.primary_key = ",".join(pk_cols)
        by_key[ent.key] = ent
        model.entities.append(ent)
    for m in _FK_RE.finditer(ddl):
        src, col, tgt, tcol = _ident(m.group(1)), m.group(2), _ident(m.group(3)), m.group(4)
        skey = ".".join(snake(x) for x in src[-2:]) if len(src) >= 2 else snake(src[-1])
        ent = by_key.get(skey) or next((e for e in model.entities if e.name == snake(src[-1])), None)
        if ent is None:
            continue
        for a in ent.attributes:
            if a.name == snake(col.strip('`"')):
                a.fk_to = ".".join([snake(x) for x in tgt[-2:]] + [snake(tcol.strip('`"'))])
    return model


