def delete_model(conn: Any, ref_model_id: int) -> None:
    ents = "SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ?"
    for stmt in (f"DELETE FROM ref_entity_concept WHERE ref_entity_id IN ({ents})",
                 f"DELETE FROM ref_entity_embedding WHERE ref_entity_id IN ({ents})",
                 f"DELETE FROM ref_attribute WHERE ref_entity_id IN ({ents})",
                 "DELETE FROM ref_relationship WHERE ref_model_id = ?",
                 "DELETE FROM ref_metric WHERE ref_model_id = ?",
                 "DELETE FROM ref_entity WHERE ref_model_id = ?",
                 "DELETE FROM ref_model WHERE ref_model_id = ?"):
        conn.execute(stmt, [ref_model_id])


def find_model(conn: Any, source: str, industry: str, flavour: str,
               version: Optional[str] = None) -> Optional[int]:
    sql = ("SELECT ref_model_id FROM ref_model WHERE source = ? AND industry = ? AND flavour = ?")
    args: list[Any] = [source, industry, flavour]
    if version:
        sql += " AND version = ?"
        args.append(version)
    row = conn.execute(sql + " ORDER BY ref_model_id DESC LIMIT 1", args).fetchone()
    return int(row[0]) if row else None


def load_model(conn: Any, model: RefModel, *, replace: bool = True) -> int:
    """Insert ``model``; replaces an earlier load of the same source/industry/flavour
    (any version) when ``replace``. Returns the new ref_model_id."""
    ensure_schema(conn)
    if replace:
        for (mid,) in conn.execute(
                "SELECT ref_model_id FROM ref_model WHERE source = ? AND industry = ? "
                "AND flavour = ?", [model.source, model.industry, model.flavour]).fetchall():
            delete_model(conn, int(mid))
    mid = conn.execute(
        "INSERT INTO ref_model (source, industry, flavour, version, name, description, "
        "origin_uri, license_note) VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING ref_model_id",
        [model.source, model.industry, model.flavour, model.version, model.name,
         model.description, model.origin_uri, model.license_note]).fetchone()[0]
    ids = _bulk_entities(conn, int(mid), model.entities)
    attr_rows: list[list[Any]] = []
    for e in model.entities:
        for i, a in enumerate(e.attributes):
            attr_rows.append([ids[e.key], i, a.name, a.data_type, a.is_pk, a.fk_to, a.tags,
                              a.description, a.reference, a.generated_ref])
    _bulk_insert(conn, "ref_attribute",
                 ["ref_entity_id", "ordinal", "name", "data_type", "is_pk", "fk_to", "tags",
                  "description", "reference", "generated_ref"], attr_rows)
    rel_rows = [[mid, ids[f], ids[t], via] for f, t, via in model.relationships()
                if f in ids and t in ids]
    _bulk_insert(conn, "ref_relationship",
                 ["ref_model_id", "from_entity_id", "to_entity_id", "via_attribute"], rel_rows)
    met_rows = [[mid, ids.get(mt.entity_key or ""), mt.name, mt.description, mt.n_dimensions,
                 mt.n_measures, mt.definition] for mt in model.metrics]
    _bulk_insert(conn, "ref_metric",
                 ["ref_model_id", "ref_entity_id", "name", "description", "n_dimensions",
                  "n_measures", "definition"], met_rows)
    return int(mid)


def _bulk_insert(conn: Any, table: str, cols: list[str], rows: list[list[Any]]) -> None:
    """Insert many rows at once through Arrow (per-row executemany is ~100x slower
    for the 270k attributes of the full MVM gallery); falls back to executemany."""
    if not rows:
        return
    try:
        import pyarrow as pa  # noqa: PLC0415
        tbl = pa.table({c: [r[i] for r in rows] for i, c in enumerate(cols)})
        conn.register("_ref_bulk", tbl)
        try:
            conn.execute(f"INSERT INTO {table} ({', '.join(cols)}) "
                         f"SELECT {', '.join(cols)} FROM _ref_bulk")
        finally:
            conn.unregister("_ref_bulk")
    except ImportError:
        conn.executemany(f"INSERT INTO {table} ({', '.join(cols)}) VALUES "
                         f"({', '.join('?' * len(cols))})", rows)


def _bulk_entities(conn: Any, mid: int, entities: Sequence[RefEntity]) -> dict[str, int]:
    """Insert entities with ids drawn from the sequence up front; returns key -> id."""
    if not entities:
        return {}
    new_ids = [int(r[0]) for r in conn.execute(
        "SELECT nextval('ref_entity_seq') FROM range(?)", [len(entities)]).fetchall()]
    ids = {e.key: i for e, i in zip(entities, new_ids)}
    _bulk_insert(conn, "ref_entity",
                 ["ref_entity_id", "ref_model_id", "entity_key", "domain", "subdomain", "name",
                  "display_name", "description", "primary_key", "standard_refs", "n_attributes"],
                 [[ids[e.key], mid, e.key, e.domain, e.subdomain, e.name, e.display_name,
                   e.description, e.primary_key, e.standard_refs, len(e.attributes)]
                  for e in entities])
    return ids


def read_model(conn: Any, ref_model_id: int) -> RefModel:
    """Rebuild a RefModel from the catalog (metrics included)."""
    row = conn.execute("SELECT source, industry, flavour, version, name, description, origin_uri, "
                       "license_note FROM ref_model WHERE ref_model_id = ?",
                       [ref_model_id]).fetchone()
    if row is None:
        raise KeyError(f"no ref_model {ref_model_id}")
    model = RefModel(*row)
    ents: dict[int, RefEntity] = {}
    for eid, domain, sub, name, disp, desc, pk, refs in conn.execute(
            "SELECT ref_entity_id, domain, subdomain, name, display_name, description, "
            "primary_key, standard_refs FROM ref_entity WHERE ref_model_id = ? "
            "ORDER BY ref_entity_id", [ref_model_id]).fetchall():
        ents[int(eid)] = RefEntity(name=name, domain=domain or "", subdomain=sub or "",
                                   display_name=disp or "", description=desc or "",
                                   primary_key=pk or "", standard_refs=refs or "")
        model.entities.append(ents[int(eid)])
    for eid, name, dt, pk, fk, tags, desc, ref in conn.execute(
            "SELECT a.ref_entity_id, a.name, a.data_type, a.is_pk, a.fk_to, a.tags, "
            "a.description, a.reference FROM ref_attribute a JOIN ref_entity e "
            "ON e.ref_entity_id = a.ref_entity_id WHERE e.ref_model_id = ? "
            "ORDER BY a.ref_entity_id, a.ordinal", [ref_model_id]).fetchall():
        ents[int(eid)].attributes.append(RefAttribute(
            name=name, data_type=dt or "", is_pk=bool(pk), fk_to=fk, tags=tags or "",
            description=desc or "", reference=ref or ""))
    keys = {i: e.key for i, e in ents.items()}
    for eid, name, desc, nd, nm, definition in conn.execute(
            "SELECT ref_entity_id, name, description, n_dimensions, n_measures, definition "
            "FROM ref_metric WHERE ref_model_id = ? ORDER BY ref_metric_id",
            [ref_model_id]).fetchall():
        model.metrics.append(RefMetric(name=name, entity_key=keys.get(eid), description=desc or "",
                                       n_dimensions=nd or 0, n_measures=nm or 0,
                                       definition=definition or ""))
    return model


def list_models(conn: Any) -> list[dict[str, Any]]:
    try:
        rows = conn.execute(
            "SELECT m.ref_model_id, m.source, m.industry, m.flavour, m.version, m.name, "
            "count(DISTINCT e.ref_entity_id), count(a.ref_attribute_id) "
            "FROM ref_model m LEFT JOIN ref_entity e USING (ref_model_id) "
            "LEFT JOIN ref_attribute a ON a.ref_entity_id = e.ref_entity_id "
            "GROUP BY ALL ORDER BY m.source, m.industry, m.flavour").fetchall()
    except Exception:  # catalog without the tables
        return []
    return [dict(zip(("ref_model_id", "source", "industry", "flavour", "version", "name",
                      "entities", "attributes"), r)) for r in rows]


