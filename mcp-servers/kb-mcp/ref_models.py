MAP_PROMPT = """You map entities of an industry data model to the data model PATTERNS
below (Silverston, Hay, Fowler, Blaha). For each entity in the batch decide which
patterns it IMPLEMENTS: an instance, role, subtype or specialization of the pattern.
A heuristic guess is given for each entity; confirm it, drop it or add better ones.
Most entities implement 1-2 patterns; reference/code tables implement Classification;
a table that copies a person's name/DOB onto a role (patient, guarantor, clinician)
implements Party Role (note that in "note"). Use only the pattern keys listed.

Write ONLY a JSON array to the output file, one object per link:
  {{"ref_entity_id": <int>, "pattern_key": "<key>", "confidence": <0.5-0.95>, "note": "<10 words>"}}
Entities with no pattern get no rows. Be thorough: every entity in the batch must be considered.

PATTERNS
{patterns}

ENTITIES (id | card | heuristic guess)
{entities}
"""


def map_batches(conn: Any, ref_model_ids: Sequence[int], catalog: PatternCatalog, *,
                batch_size: int = 25) -> list[dict[str, Any]]:
    """Batches for the subagent pass: [{"batch": n, "prompt": str, "entity_ids": [...]}]."""
    pats = "\n".join(f"- {p.key}: {p.name}. {p.description}" for p in catalog.patterns)
    items: list[tuple[int, str, str]] = []
    for mid in ref_model_ids:
        m = read_model(conn, mid)
        ids = [r[0] for r in conn.execute(
            "SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ? ORDER BY ref_entity_id",
            [mid]).fetchall()]
        guesses = entity_patterns(conn, mid, min_confidence=0.0)
        for eid, e in zip(ids, m.entities):
            g = ", ".join(f"{k} {c:.2f}" for k, c, _ in guesses.get(e.key, [])) or "none"
            items.append((int(eid), entity_card(e, max_attrs=25, max_desc=300), g))
    out = []
    for n, i in enumerate(range(0, len(items), batch_size), start=1):
        chunk = items[i:i + batch_size]
        ents = "\n".join(f"{eid} | {card} | {g}" for eid, card, g in chunk)
        out.append({"batch": n, "entity_ids": [c[0] for c in chunk],
                    "prompt": MAP_PROMPT.format(patterns=pats, entities=ents)})
    return out


def apply_mapping(conn: Any, rows: Iterable[dict[str, Any]], catalog: PatternCatalog, *,
                  allowed_ids: Optional[set[int]] = None, resolver: Any = None
                  ) -> tuple[int, list[str]]:
    """Write subagent links (method='subagent'); they replace heuristic rows for the
    same entity. Returns (rows written, problems)."""
    ensure_schema(conn)
    keys = {p.key for p in catalog.patterns}
    concept_ids = resolve_pattern_concepts(catalog, resolver) if resolver else {}
    problems: list[str] = []
    by_entity: dict[int, list[tuple[str, float, str]]] = {}
    for r in rows:
        try:
            eid, key = int(r["ref_entity_id"]), str(r["pattern_key"])
            conf = max(0.5, min(0.95, float(r.get("confidence", 0.7))))
        except (KeyError, TypeError, ValueError):
            problems.append(f"bad row: {r!r}"[:200])
            continue
        if key not in keys:
            problems.append(f"unknown pattern {key!r} for entity {eid}")
            continue
        if allowed_ids is not None and eid not in allowed_ids:
            problems.append(f"entity {eid} not in this batch")
            continue
        by_entity.setdefault(eid, []).append((key, conf, str(r.get("note") or "")[:200]))
    # Every entity the batch covered is re-decided, including ones the subagent
    # gave no pattern: their earlier heuristic guesses are cleared too.
    for eid in sorted(set(by_entity) | set(allowed_ids or ())):
        conn.execute("DELETE FROM ref_entity_concept WHERE ref_entity_id = ? "
                     "AND method IN ('heuristic', 'subagent')", [eid])
    n = 0
    for eid, links in by_entity.items():
        seen = set()
        for key, conf, note in links:
            if key in seen:
                continue
            seen.add(key)
            conn.execute("INSERT INTO ref_entity_concept VALUES (?, ?, ?, ?, 'subagent', ?)",
                         [eid, key, concept_ids.get(key), conf, note])
            n += 1
    return n, problems
