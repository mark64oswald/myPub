SCHEMA_SQL = [
    "CREATE SEQUENCE IF NOT EXISTS ref_model_seq START 1",
    "CREATE SEQUENCE IF NOT EXISTS ref_entity_seq START 1",
    "CREATE SEQUENCE IF NOT EXISTS ref_attribute_seq START 1",
    "CREATE SEQUENCE IF NOT EXISTS ref_metric_seq START 1",
    """CREATE TABLE IF NOT EXISTS ref_model (
        ref_model_id   BIGINT PRIMARY KEY DEFAULT nextval('ref_model_seq'),
        source         VARCHAR NOT NULL,    -- databricks | silverston | omop | generated | user
        industry       VARCHAR NOT NULL,    -- healthcare, health_insurance, ...
        flavour        VARCHAR NOT NULL,    -- mvm | ecm | book | cdm | ...
        version        VARCHAR NOT NULL,
        name           VARCHAR,
        description    VARCHAR,
        origin_uri     VARCHAR,             -- repo path, book title + appendix, URL
        license_note   VARCHAR,
        loaded_at      TIMESTAMP DEFAULT current_timestamp
    )""",
    """CREATE TABLE IF NOT EXISTS ref_entity (
        ref_entity_id  BIGINT PRIMARY KEY DEFAULT nextval('ref_entity_seq'),
        ref_model_id   BIGINT NOT NULL,
        entity_key     VARCHAR NOT NULL,    -- domain.name (unique within a model)
        domain         VARCHAR,
        subdomain      VARCHAR,
        name           VARCHAR NOT NULL,    -- snake_case
        display_name   VARCHAR,
        description    VARCHAR,
        primary_key    VARCHAR,
        standard_refs  VARCHAR,
        n_attributes   INTEGER
    )""",
    """CREATE TABLE IF NOT EXISTS ref_attribute (
        ref_attribute_id BIGINT PRIMARY KEY DEFAULT nextval('ref_attribute_seq'),
        ref_entity_id  BIGINT NOT NULL,
        ordinal        INTEGER,
        name           VARCHAR NOT NULL,
        data_type      VARCHAR,
        is_pk          BOOLEAN DEFAULT FALSE,
        fk_to          VARCHAR,             -- target as written (domain.entity.column or ENTITY)
        tags           VARCHAR,
        description    VARCHAR,
        reference      VARCHAR,
        generated_ref  BOOLEAN DEFAULT FALSE
    )""",
    """CREATE TABLE IF NOT EXISTS ref_relationship (
        ref_model_id   BIGINT NOT NULL,
        from_entity_id BIGINT NOT NULL,
        to_entity_id   BIGINT NOT NULL,
        via_attribute  VARCHAR,
        kind           VARCHAR DEFAULT 'fk'
    )""",
    """CREATE TABLE IF NOT EXISTS ref_metric (
        ref_metric_id  BIGINT PRIMARY KEY DEFAULT nextval('ref_metric_seq'),
        ref_model_id   BIGINT NOT NULL,
        ref_entity_id  BIGINT,
        name           VARCHAR,
        description    VARCHAR,
        n_dimensions   INTEGER,
        n_measures     INTEGER,
        definition     VARCHAR
    )""",
    """CREATE TABLE IF NOT EXISTS ref_entity_embedding (
        ref_entity_id  BIGINT PRIMARY KEY,
        embedding      FLOAT[384]
    )""",
    """CREATE TABLE IF NOT EXISTS ref_entity_concept (
        ref_entity_id  BIGINT NOT NULL,
        pattern_key    VARCHAR NOT NULL,
        concept_id     BIGINT,              -- the pattern's catalog concept, when resolved
        confidence     DOUBLE,
        method         VARCHAR,             -- heuristic | subagent | curated
        note           VARCHAR,
        PRIMARY KEY (ref_entity_id, pattern_key)
    )""",
]


def ensure_schema(conn: Any) -> None:
    for stmt in SCHEMA_SQL:
        conn.execute(stmt)


