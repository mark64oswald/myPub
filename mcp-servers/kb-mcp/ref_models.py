def parse_databricks_model(path: Path, *, industry: Optional[str] = None,
                           flavour: Optional[str] = None) -> RefModel:
    """Parse one Databricks ``model.json`` (data-models/<industry>/<vN>/<flavour>/model.json)."""
    path = Path(path)
    doc = json.loads(path.read_text())
    m = doc.get("model", doc)
    parts = path.parts
    flavour = flavour or (parts[-2] if len(parts) >= 2 else "mvm")
    version = m.get("version") or (parts[-3] if len(parts) >= 3 else "v1")
    industry = industry or (parts[-4] if len(parts) >= 4 else snake(m.get("name", "model")))
    model = RefModel(
        source="databricks", industry=industry, flavour=flavour, version=str(version),
        name=m.get("name") or industry, description=m.get("description") or "",
        origin_uri=f"databricks-industry-solutions/lakehouse-industry-data-models:"
                   f"data-models/{industry}/{parts[-3] if len(parts) >= 3 else version}/{flavour}",
        license_note="Databricks License: use only with Databricks Services; local catalog only.",
    )
    for d in m.get("domains") or []:
        dname = d.get("name") or ""
        for p in d.get("products") or []:
            ent = RefEntity(
                name=p.get("table_name") or p.get("name"), domain=dname,
                subdomain=p.get("subdomain") or "", display_name=p.get("name") or "",
                description=p.get("description") or "", primary_key=p.get("primary_key") or "",
                standard_refs=p.get("reference") or "")
            for a in p.get("attributes") or []:
                col = a.get("column_name") or a.get("name")
                ent.attributes.append(RefAttribute(
                    name=col, data_type=a.get("type") or "",
                    is_pk=bool(col and col == ent.primary_key),
                    fk_to=a.get("foreign_key_to") or None, tags=a.get("tags") or "",
                    description=a.get("description") or "",
                    reference=a.get("references") or a.get("reference") or ""))
            model.entities.append(ent)
    for mv in m.get("metric_views") or []:
        owner = mv.get("owner_domain"), mv.get("owner_product")
        model.metrics.append(RefMetric(
            name=mv.get("view_name") or "", description=mv.get("description") or "",
            entity_key=f"{owner[0]}.{owner[1]}" if all(owner) else None,
            n_dimensions=int(mv.get("dimensions_count") or 0),
            n_measures=int(mv.get("measures_count") or 0), definition=mv.get("sql") or ""))
    return model


_YES = {"yes", "y", "true", "1", "x", "pk", "fk"}


def parse_silverston_csv(text: str, *, industry: str, book_title: str = "",
                         appendix: str = "") -> RefModel:
    """Parse a transcribed Silverston appendix: ``entity,attribute,pk,fk,domain``.

    The book's listing leaves the entity cell blank on continuation rows, so
    a blank entity carries the previous one forward. FK targets aren't
    printed; they resolve later by matching the attribute name to another
    entity's PK ("PARTY ID" -> PARTY), which ``RefModel.relationships`` does.
    Silverston's attribute "domain" (ID, Datetime, Description...) is kept
    as the data type.
    """
    reader = csv.DictReader(io.StringIO(text.lstrip("﻿")))
    cols = {(c or "").strip().lower(): c for c in reader.fieldnames or []}

    def get(row: dict, *names: str) -> str:
        for n in names:
            if n in cols:
                return (row.get(cols[n]) or "").strip()
        return ""

    model = RefModel(source="silverston", industry=industry, flavour="book", version="rev-2001",
                     name=f"{industry.replace('_', ' ').title()} (Silverston Vol. 2)",
                     origin_uri=f"{book_title}{' — ' + appendix if appendix else ''}",
                     license_note="Transcribed from a book in Mark's library; local catalog only.")
    by_name: dict[str, RefEntity] = {}
    current: Optional[RefEntity] = None
    for row in reader:
        ename = get(row, "entity", "entity name", "entity_name")
        attr = get(row, "attribute", "attribute name", "attribute_name")
        if ename:
            key = snake(ename)
            current = by_name.get(key)
            if current is None:
                current = RefEntity(name=key, display_name=ename.upper(), domain="")
                by_name[key] = current
                model.entities.append(current)
        if current is None or not attr:
            continue
        is_pk = get(row, "pk", "pk?").lower() in _YES
        is_fk = get(row, "fk", "fk?").lower() in _YES
        aname = snake(attr)
        if any(a.name == aname for a in current.attributes):
            continue
        current.attributes.append(RefAttribute(
            name=aname, data_type=get(row, "domain", "type"), is_pk=is_pk,
            fk_to=aname if is_fk else None))
    for e in model.entities:
        pks = [a.name for a in e.attributes if a.is_pk]
        own = f"{e.name}_id"
        e.primary_key = own if own in pks else (pks[0] if len(pks) == 1 else ",".join(pks))
        # An entity's own key is never an FK to itself.
        for a in e.attributes:
            if a.fk_to == own:
                a.fk_to = None
    return model


OMOP_FIELD_CSV = ("https://raw.githubusercontent.com/OHDSI/CommonDataModel/main/inst/csv/"
                  "OMOP_CDMv5.4_Field_Level.csv")
OMOP_TABLE_CSV = ("https://raw.githubusercontent.com/OHDSI/CommonDataModel/main/inst/csv/"
                  "OMOP_CDMv5.4_Table_Level.csv")


def parse_omop(field_csv: str, table_csv: str = "", *, version: str = "5.4") -> RefModel:
    """Parse the OHDSI CDM field-level (and optional table-level) CSVs."""
    model = RefModel(source="omop", industry="healthcare", flavour="cdm", version=version,
                     name=f"OMOP Common Data Model v{version}",
                     origin_uri="OHDSI/CommonDataModel:inst/csv", license_note="Apache 2.0")
    schemas: dict[str, tuple[str, str]] = {}
    if table_csv:
        for row in csv.DictReader(io.StringIO(table_csv.lstrip("﻿"))):
            t = (row.get("cdmTableName") or "").strip().lower()
            schemas[t] = ((row.get("schema") or "").strip().lower(),
                          (row.get("tableDescription") or "").strip())
    by_name: dict[str, RefEntity] = {}
    for row in csv.DictReader(io.StringIO(field_csv.lstrip("﻿"))):
        t = (row.get("cdmTableName") or "").strip().lower()
        if not t:
            continue
        ent = by_name.get(t)
        if ent is None:
            schema, desc = schemas.get(t, ("cdm", ""))
            ent = RefEntity(name=t, domain=schema or "cdm", display_name=t.upper(),
                            description=desc)
            by_name[t] = ent
            model.entities.append(ent)
        col = (row.get("cdmFieldName") or "").strip().lower()
        is_pk = (row.get("isPrimaryKey") or "").upper() == "TRUE"
        fk_table = (row.get("fkTableName") or "").strip()
        fk = None
        if (row.get("isForeignKey") or "").upper() == "TRUE" and fk_table not in ("", "NA"):
            fk = f"{fk_table.lower()}.{(row.get('fkFieldName') or '').strip().lower()}"
        if is_pk:
            ent.primary_key = col
        ent.attributes.append(RefAttribute(
            name=col, data_type=(row.get("cdmDatatype") or "").strip(), is_pk=is_pk, fk_to=fk,
            description=(row.get("userGuidance") or "").strip()))
    # OMOP FKs name the table only; give them the target's schema as domain.
    keys = {e.name: e.key for e in model.entities}
    for e in model.entities:
        for a in e.attributes:
            if a.fk_to:
                t, _, c = a.fk_to.partition(".")
                if t in keys:
                    a.fk_to = f"{keys[t]}.{c}"
    return model


