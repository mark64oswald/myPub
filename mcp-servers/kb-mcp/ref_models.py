"""ref_models.py — Reference data models as structured metadata (2026-11).

A small metamodel that holds industry data models from three kinds of
source side by side, so they can be compared, reviewed and composed:

* ``databricks`` — the Lakehouse Industry Data Models (``model.json`` per
  industry/flavour, generated by Databricks' Vibe Data Modeling agent;
  Databricks License, loaded into the local catalog only);
* ``silverston`` — The Data Model Resource Book, Vol. 2 appendices
  (entities and attributes per industry), transcribed from the book's page
  images into CSV on Mark's Mac (book copyright, local only);
* ``omop`` — the OHDSI OMOP Common Data Model field-level CSV (Apache 2.0).

Generated models are *not* sections or concepts: 886k generated attributes
would swamp the concept graph and add nothing to retrieval. Instead each
entity is a row with its attributes and foreign keys, an entity "card"
(name, domain, description, attribute names) gets an embedding for
similarity search, and ``ref_entity_concept`` links entities to the data
model *patterns* the books teach (data/ref_models/patterns.yaml). That
link is what /kb-model-review and /kb-domain-model reason over.

Tables (created by ``ensure_schema``; idempotent):

    ref_model            one row per loaded model (source, industry, flavour, version)
    ref_entity           entities / tables / products
    ref_attribute        attributes / columns, with PK flag and FK target text
    ref_relationship     resolved FKs between entities of the same model
    ref_metric           metric views (Databricks) — YAML body kept as text
    ref_entity_embedding entity-card embeddings (FLOAT[384], MiniLM)
    ref_entity_concept   entity -> pattern link (pattern_key, concept_id, confidence, method)

Everything here is deterministic; the only LLM step (confirming pattern
links) runs as Claude Code subagents through scripts/load_ref_models.py.
"""

