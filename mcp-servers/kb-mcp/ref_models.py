def entity_card(e: RefEntity, *, max_attrs: int = 30, max_desc: int = 400) -> str:
    """Short text that stands for an entity in similarity search and subagent prompts."""
    head = f"{e.name.replace('_', ' ')}"
    if e.domain:
        head += f" ({e.domain.replace('_', ' ')})"
    desc = re.sub(r"\s+", " ", e.description or "").strip()[:max_desc]
    attrs = ", ".join(a.name for a in e.attributes[:max_attrs])
    return f"{head}. {desc} Attributes: {attrs}".strip()


def embed_entities(conn: Any, model_ids: Sequence[int], embedder: Any, *,
                   batch: int = 256) -> int:
    """(Re)embed entity cards for the given models. Returns rows written."""
    ensure_schema(conn)
    n = 0
    for mid in model_ids:
        m = read_model(conn, mid)
        ids = [r[0] for r in conn.execute(
            "SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ? ORDER BY ref_entity_id",
            [mid]).fetchall()]
        cards = [entity_card(e) for e in m.entities]
        conn.execute("DELETE FROM ref_entity_embedding WHERE ref_entity_id IN "
                     "(SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ?)", [mid])
        for i in range(0, len(cards), batch):
            vecs = embedder.encode(cards[i:i + batch], normalize_embeddings=True)
            conn.executemany("INSERT INTO ref_entity_embedding VALUES (?, ?)",
                             [[int(eid), [float(x) for x in v]]
                              for eid, v in zip(ids[i:i + batch], vecs)])
            n += len(vecs)
    return n


def similar_entities(conn: Any, vector: Sequence[float], *, limit: int = 20,
                     sources: Optional[Sequence[str]] = None,
                     industries: Optional[Sequence[str]] = None) -> list[dict[str, Any]]:
    """Nearest entity cards by cosine similarity (vectors are normalized)."""
    sql = ("SELECT e.ref_entity_id, m.source, m.industry, m.flavour, e.entity_key, e.name, "
           "e.domain, e.description, list_dot_product(x.embedding, ?::FLOAT[384]) AS sim "
           "FROM ref_entity_embedding x JOIN ref_entity e USING (ref_entity_id) "
           "JOIN ref_model m USING (ref_model_id) WHERE 1=1")
    args: list[Any] = [list(vector)]
    if sources:
        sql += f" AND m.source IN ({','.join('?' * len(sources))})"
        args += list(sources)
    if industries:
        sql += f" AND m.industry IN ({','.join('?' * len(industries))})"
        args += list(industries)
    sql += " ORDER BY sim DESC LIMIT ?"
    args.append(limit)
    cols = ("ref_entity_id", "source", "industry", "flavour", "entity_key", "name", "domain",
            "description", "similarity")
    return [dict(zip(cols, r)) for r in conn.execute(sql, args).fetchall()]


