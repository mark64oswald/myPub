@dataclass
class RefAttribute:
    name: str
    data_type: str = ""
    is_pk: bool = False
    fk_to: Optional[str] = None
    tags: str = ""
    description: str = ""
    reference: str = ""

    @property
    def generated_ref(self) -> bool:
        return bool(GENERATED_REF.search(self.reference or ""))


@dataclass
class RefMetric:
    name: str
    entity_key: Optional[str] = None
    description: str = ""
    n_dimensions: int = 0
    n_measures: int = 0
    definition: str = ""


@dataclass
class RefEntity:
    name: str
    domain: str = ""
    subdomain: str = ""
    display_name: str = ""
    description: str = ""
    primary_key: str = ""
    standard_refs: str = ""
    attributes: list[RefAttribute] = field(default_factory=list)

    @property
    def key(self) -> str:
        return f"{self.domain}.{self.name}" if self.domain else self.name


@dataclass
class RefModel:
    source: str
    industry: str
    flavour: str
    version: str
    name: str = ""
    description: str = ""
    origin_uri: str = ""
    license_note: str = ""
    entities: list[RefEntity] = field(default_factory=list)
    metrics: list[RefMetric] = field(default_factory=list)

    def entity_index(self) -> dict[str, RefEntity]:
        return {e.key: e for e in self.entities}

    def relationships(self) -> list[tuple[str, str, str]]:
        """(from_key, to_key, via_attribute) for every FK that resolves inside the model."""
        by_key = self.entity_index()
        by_name: dict[str, list[str]] = {}
        by_pk: dict[str, list[str]] = {}
        for e in self.entities:
            by_name.setdefault(e.name, []).append(e.key)
            if e.primary_key:
                by_pk.setdefault(e.primary_key, []).append(e.key)
        out = []
        for e in self.entities:
            for a in e.attributes:
                if not a.fk_to:
                    continue
                target = resolve_fk_target(a.fk_to, by_key, by_name, by_pk)
                if target:
                    out.append((e.key, target, a.name))
        return out


def snake(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", (text or "").strip().lower()).strip("_")


def resolve_fk_target(fk_to: str, by_key: dict[str, Any], by_name: dict[str, list[str]],
                      by_pk: dict[str, list[str]]) -> Optional[str]:
    """Resolve an FK target as written to an entity key in the same model.

    Accepts ``domain.entity.column`` (Databricks), ``domain.entity``,
    ``entity`` and, as a last resort, a bare column name that is some
    entity's primary key (Silverston's "PARTY ID" style)."""
    parts = [p for p in fk_to.split(".") if p]
    if len(parts) >= 2 and f"{parts[0]}.{parts[1]}" in by_key:
        return f"{parts[0]}.{parts[1]}"
    for cand in (parts[-2] if len(parts) >= 2 else None, parts[0] if parts else None):
        if cand and len(by_name.get(cand, [])) == 1:
            return by_name[cand][0]
    col = snake(parts[-1]) if parts else ""
    if len(by_pk.get(col, [])) == 1:
        return by_pk[col][0]
    return None


