@dataclass
class Pattern:
    key: str
    name: str
    aliases: list[str]
    description: str
    names: list[re.Pattern]
    attrs: list[re.Pattern]
    books: list[dict[str, Any]]
    review: Optional[str] = None
    # Column-name evidence groups: a table counts for a review check only when
    # every group matches one of its columns (see model_review_gen.has_evidence).
    evidence: list[list[re.Pattern]] = field(default_factory=list)

    def concept_names(self) -> list[str]:
        return [self.name] + self.aliases


@dataclass
class PatternCatalog:
    patterns: list[Pattern]
    books: dict[str, str]

    def get(self, key: str) -> Pattern:
        for p in self.patterns:
            if p.key == key:
                return p
        raise KeyError(key)

    def book_title(self, ref: str) -> str:
        return self.books.get(ref, ref)


def _rx(items: Iterable[str]) -> list[re.Pattern]:
    return [re.compile(rf"(?:{s})") for s in items or []]


def load_patterns(path: Path = PATTERNS_FILE) -> PatternCatalog:
    doc = yaml.safe_load(Path(path).read_text())
    pats = [Pattern(key=p["key"], name=p["name"], aliases=list(p.get("aliases") or []),
                    description=" ".join((p.get("description") or "").split()),
                    names=_rx(p.get("names")), attrs=_rx(p.get("attrs")),
                    books=list(p.get("books") or []), review=p.get("review"),
                    evidence=[_rx(g) for g in p.get("evidence") or []])
            for p in doc.get("patterns") or []]
    return PatternCatalog(patterns=pats, books=dict(doc.get("books") or {}))


def _name_suffixes(name: str) -> list[str]:
    parts = name.split("_")
    return ["_".join(parts[i:]) for i in range(len(parts))]


def classify_entity(e: RefEntity, catalog: PatternCatalog) -> list[tuple[str, float, str]]:
    """Heuristic pattern links for one entity: [(pattern_key, confidence, reason)].

    A name hit (the whole snake_case name, or one of its "_" suffixes, fully
    matches a pattern regex) scores 0.6; a whole-name hit on the *full*
    name scores 0.65. Without a name hit, two or more attribute hints score
    0.45."""
    out: list[tuple[str, float, str]] = []
    name = snake(e.name)
    suffixes = _name_suffixes(name)
    attr_names = [snake(a.name) for a in e.attributes]
    for p in catalog.patterns:
        hit = next((rx.pattern for rx in p.names if rx.fullmatch(name)), None)
        if hit:
            out.append((p.key, 0.65, f"name '{name}' matches {hit}"))
            continue
        hit = next(((s, rx.pattern) for s in suffixes[1:] for rx in p.names if rx.fullmatch(s)),
                   None)
        if hit:
            out.append((p.key, 0.6, f"name suffix '{hit[0]}' matches {hit[1]}"))
            continue
        if p.attrs:
            hits = sorted({a for a in attr_names for rx in p.attrs if rx.fullmatch(a)})
            if len(hits) >= 2:
                out.append((p.key, 0.45, "attributes " + ", ".join(hits[:4])))
    return out


PERSON_ATTRS = re.compile(r"(first|last|middle|given|family|full|legal)_name|birth_date|"
                          r"date_of_birth|dob|ssn|gender|sex(_at_birth)?")


def carries_person_identity(e: RefEntity) -> list[str]:
    """Attribute names that copy person identity onto an entity (name, DOB, SSN...)."""
    return [a.name for a in e.attributes if PERSON_ATTRS.search(snake(a.name))]


def classify_model(conn: Any, ref_model_id: int, catalog: PatternCatalog, *,
                   resolver: Any = None) -> int:
    """Write heuristic ref_entity_concept rows for a model; keeps subagent/curated rows.

    ``resolver`` (an EntityResolver) maps each pattern to its catalog concept by
    name/alias, lookup only; without one, concept_id stays NULL."""
    ensure_schema(conn)
    concept_ids = resolve_pattern_concepts(catalog, resolver) if resolver else {}
    m = read_model(conn, ref_model_id)
    ids = [r[0] for r in conn.execute(
        "SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ? ORDER BY ref_entity_id",
        [ref_model_id]).fetchall()]
    conn.execute("DELETE FROM ref_entity_concept WHERE method = 'heuristic' AND ref_entity_id IN "
                 "(SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ?)", [ref_model_id])
    kept = {(int(a), b) for a, b in conn.execute(
        "SELECT ref_entity_id, pattern_key FROM ref_entity_concept WHERE ref_entity_id IN "
        "(SELECT ref_entity_id FROM ref_entity WHERE ref_model_id = ?)", [ref_model_id]).fetchall()}
    rows = []
    for eid, e in zip(ids, m.entities):
        links = classify_entity(e, catalog)
        keys = {k for k, _c, _r in links}
        person = carries_person_identity(e)
        if len(person) >= 2 and "party" not in keys and "party_role" not in keys:
            links.append(("party_role", 0.45, "carries person identity: " + ", ".join(person[:4])))
        for key, conf, reason in links:
            if (int(eid), key) in kept:
                continue
            rows.append([int(eid), key, concept_ids.get(key), conf, "heuristic", reason])
    if rows:
        conn.executemany("INSERT INTO ref_entity_concept VALUES (?, ?, ?, ?, ?, ?)", rows)
    return len(rows)


def resolve_pattern_concepts(catalog: PatternCatalog, resolver: Any) -> dict[str, int]:
    out: dict[str, int] = {}
    for p in catalog.patterns:
        for n in p.concept_names():
            try:
                cid = resolver.resolve_lookup_only(n)
            except Exception:  # catalog without concept tables (tests, fresh installs)
                return out
            if cid is not None:
                out[p.key] = int(cid)
                break
    return out


def entity_patterns(conn: Any, ref_model_id: int, *, min_confidence: float = 0.5
                    ) -> dict[str, list[tuple[str, float, str]]]:
    """entity_key -> [(pattern_key, confidence, method)], best first."""
    out: dict[str, list[tuple[str, float, str]]] = {}
    try:
        rows = conn.execute(
            "SELECT e.entity_key, c.pattern_key, c.confidence, c.method FROM ref_entity_concept c "
            "JOIN ref_entity e USING (ref_entity_id) WHERE e.ref_model_id = ? "
            "AND c.confidence >= ? ORDER BY c.confidence DESC", [ref_model_id, min_confidence]
        ).fetchall()
    except Exception:
        return out
    for key, pk, conf, method in rows:
        out.setdefault(key, []).append((pk, float(conf), method))
    return out


